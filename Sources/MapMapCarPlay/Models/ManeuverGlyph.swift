import CarPlay
import Foundation
import UIKit

/// Maps the OSRM-style `maneuverType`/`maneuverModifier` strings carried on
/// ``BannerLine`` (see `crates/sn-valhalla/src/translate.rs`,
/// `map_maneuver_type`: types `depart`, `arrive`, `turn`, `new name`,
/// `continue`, `on ramp`, `off ramp`, `fork`, `merge`, `roundabout`,
/// `rotary`, `exit roundabout`, `exit rotary`, `notification`; modifiers
/// `straight`, `slight left`/`left`/`sharp left`, `slight right`/`right`/
/// `sharp right`, `uturn`), plus the manoeuvre's driving side
/// (``VisualBanner/drivingSide``), onto MapMap's own direction icons for
/// `CPManeuver.symbolImage` and onto CarPlay's `CPManeuverType`.
///
/// The icons are the approved MapMap set (`map-assets/icons/directions/`),
/// shipped in this module's `DirectionIcons.xcassets` as vector PDF template
/// images (generated by `map-assets/icons/directions/generate-native.mjs`).
/// Every transform, including the left-hand-traffic mirror, is baked into
/// the geometry, so CarPlay's image snapshot cannot lose a mirroring flag.
/// Secondary road furniture carries 0.35 alpha, which a template image
/// keeps: CarPlay tints the glyph for its light or dark card and the
/// untravelled part of a roundabout stays the same colour, fainter.
public enum ManeuverGlyph {

    // MARK: - Icon name (mirror of the canonical mapping)

    private static let modifierSuffix: [String: String] = [
        "left": "left",
        "right": "right",
        "sharp left": "sharp_left",
        "sharp right": "sharp_right",
        "slight left": "slight_left",
        "slight right": "slight_right",
        "straight": "straight",
        "uturn": "uturn",
    ]

    private static let typeBase: [String: String] = [
        "turn": "turn",
        "new name": "new_name",
        "depart": "depart",
        "arrive": "arrive",
        "merge": "merge",
        "on ramp": "on_ramp",
        "off ramp": "off_ramp",
        "fork": "fork",
        "end of road": "end_of_road",
        "continue": "continue",
        "roundabout": "roundabout",
        "rotary": "rotary",
        "roundabout turn": "turn",
        "exit roundabout": "roundabout",
        "exit rotary": "rotary",
        "use lane": "turn",
        "notification": "notification",
        "invalid": "invalid",
        "ferry": "ferry",
        "uturn": "uturn",
    ]

    /// Icon families drawn as a ring: they need the driving side.
    private static let ringBases: Set<String> = ["roundabout", "rotary"]

    /// Normalises an engine-supplied driving side: `"left"` (UK-style
    /// left-hand traffic, roundabouts clockwise) or `"right"`. Anything
    /// else, including `nil`, is unknown and returns `nil`: never a guess.
    public static func drivingSide(_ value: String?) -> String? {
        let v = (value ?? "").trimmingCharacters(in: .whitespaces).lowercased()
        return v == "left" || v == "right" ? v : nil
    }

    /// The MapMap direction icon name (`turn_left`,
    /// `rotary_lht_slight_left`, ...) for a manoeuvre. A mirror of the
    /// canonical `iconNameForManeuver(type, modifier, drivingSide)` in
    /// `map-assets/icons/directions/generate.mjs`; `ManeuverGlyphTests`
    /// checks it against a golden table generated from the canonical
    /// function, so the two cannot drift silently.
    ///
    /// There is no default driving side. A roundabout or rotary with a
    /// known side draws its ring in that circulation; with the side unknown
    /// it draws the plain turn glyph for its exit direction, and a u-turn
    /// the plain `continue_uturn`, never a guessed ring. Always returns a
    /// name with a bundled image.
    public static func iconName(maneuverType: String?, maneuverModifier: String?, drivingSide: String?) -> String {
        let norm: (String?) -> String = { ($0 ?? "").trimmingCharacters(in: .whitespaces).lowercased() }
        let base = typeBase[norm(maneuverType)] ?? "turn"
        let suffix = modifierSuffix[norm(maneuverModifier)] ?? ""
        let side = Self.drivingSide(drivingSide)
        func pick(_ candidates: [String]) -> String {
            candidates.first { !$0.isEmpty && DirectionIconNames.all.contains($0) } ?? "turn_straight"
        }
        if ringBases.contains(base) {
            guard let side else {
                // Unknown side: a plain glyph for the direction, never a guessed ring.
                if suffix == "uturn" { return "continue_uturn" }
                return pick([suffix.isEmpty ? "" : "turn_\(suffix)", "turn_straight"])
            }
            let lht = side == "left" ? "_lht" : ""
            return pick([
                suffix.isEmpty ? "\(base)\(lht)" : "\(base)\(lht)_\(suffix)",
                // rotary has no u-turn drawing of its own; the roundabout one is it.
                suffix.isEmpty ? "" : "roundabout\(lht)_\(suffix)",
                "\(base)\(lht)",
                "roundabout\(lht)",
            ])
        }
        if suffix == "uturn" || base == "uturn" {
            if base == "continue" { return "continue_uturn" }
            switch side {
            case "left": return "uturn_right"
            case "right": return "uturn_left"
            default: return "continue_uturn"
            }
        }
        return pick([
            suffix.isEmpty ? base : "\(base)_\(suffix)",
            base,
            suffix.isEmpty ? "" : "turn_\(suffix)",
            "turn_straight",
        ])
    }

    // MARK: - Images

    /// Point size the maneuver symbol is rendered at: the CarPlay Developer
    /// Guide's maximum for a first maneuver symbol (50 x 50 pt).
    public static let symbolPointSize: CGFloat = 50

    /// The bundled vector icon `name`, unsized, as a template image.
    public static func vectorImage(named name: String) -> UIImage? {
        UIImage(named: "mm_dir_\(name)", in: .module, compatibleWith: nil)?
            .withRenderingMode(.alwaysTemplate)
    }

    /// The icon `name` rendered from its vector data at `pointSize` (3x, so
    /// it is sharp on every CarPlay screen), as a template image: CarPlay
    /// supplies the colour, the alpha (including the 0.35 secondary) is
    /// the icon's own.
    public static func image(named name: String, pointSize: CGFloat = symbolPointSize) -> UIImage? {
        guard let vector = vectorImage(named: name) else { return nil }
        let format = UIGraphicsImageRendererFormat()
        format.scale = 3
        format.opaque = false
        let size = CGSize(width: pointSize, height: pointSize)
        return UIGraphicsImageRenderer(size: size, format: format)
            .image { _ in vector.draw(in: CGRect(origin: .zero, size: size)) }
            .withRenderingMode(.alwaysTemplate)
    }

    /// The symbol image for a manoeuvre (see ``iconName(maneuverType:maneuverModifier:drivingSide:)``).
    public static func symbolImage(maneuverType: String?, maneuverModifier: String?, drivingSide: String?) -> UIImage? {
        image(named: iconName(maneuverType: maneuverType, maneuverModifier: maneuverModifier, drivingSide: drivingSide))
    }

    // MARK: - CarPlay metadata

    /// `true` for the roundabout/rotary family of OSRM types.
    static func isRoundabout(_ maneuverType: String?) -> Bool {
        ["roundabout", "rotary", "exit roundabout", "exit rotary"].contains(maneuverType ?? "")
    }

    /// The nearest `CPManeuverType`, for apps that also want the system's
    /// own presentation styling (`CPManeuver.maneuverType`, iOS 17.4+).
    /// Several MapMap/OSRM types have no exact CarPlay counterpart
    /// (`merge`, `notification`) and fall back to `.followRoad`.
    @available(iOS 17.4, *)
    public static func cpManeuverType(maneuverType: String?, maneuverModifier: String?) -> CPManeuverType {
        switch maneuverType {
        case "depart":
            return maneuverModifier == "uturn" ? .startRouteWithUTurn : .startRoute
        case "arrive":
            switch maneuverModifier {
            case "left": return .arriveAtDestinationLeft
            case "right": return .arriveAtDestinationRight
            default: return .arriveAtDestination
            }
        case "roundabout", "rotary":
            return .enterRoundabout
        case "exit roundabout", "exit rotary":
            return .exitRoundabout
        case "on ramp":
            return .onRamp
        case "off ramp":
            switch maneuverModifier {
            case "left": return .highwayOffRampLeft
            case "right": return .highwayOffRampRight
            default: return .offRamp
            }
        case "fork":
            switch maneuverModifier {
            case "slight left", "left": return .keepLeft
            case "slight right", "right": return .keepRight
            default: return .followRoad
            }
        case "continue":
            return maneuverModifier == "uturn" ? .uTurn : .followRoad
        case "turn":
            switch maneuverModifier {
            case "uturn": return .uTurn
            case "sharp left": return .sharpLeftTurn
            case "left": return .leftTurn
            case "slight left": return .slightLeftTurn
            case "straight": return .straightAhead
            case "slight right": return .slightRightTurn
            case "right": return .rightTurn
            case "sharp right": return .sharpRightTurn
            default: return .followRoad
            }
        default:
            return .followRoad
        }
    }
}
